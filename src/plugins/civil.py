# 英文/拼音类脏话按词边界匹配，避免误伤（如 sb 出现在 URL 里）
_ASCII = ("sb", "cnm", "cnmb", "nmsl", "tnnd")
_ASCII_RE = re.compile(r"(?<![a-z0-9])(" + "|".join(map(re.escape, _ASCII)) + r")(?![a-z0-9])")


def _hit(event: MessageEvent) -> bool:
    if event.message_type != "group":
        return False
    if event.user_id == event.self_id:  # 不理会自己
        return False
    text = event.get_message().extract_plain_text().lower()
    if any(w in text for w in BAD_WORDS):
        return True
    return bool(_ASCII_RE.search(text))


civil = on_message(rule=Rule(_hit), priority=5, block=False)


@civil.handle()
async def handle_civil(event: MessageEvent):
    await civil.finish(MessageSegment.at(event.user_id) + " " + random.choice(POEMS))
